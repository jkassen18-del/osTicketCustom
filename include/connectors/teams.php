    /* ------------------- Cards ------------------- */

    protected function card($title, array $facts, $text='', $url=null, $subtitle=null, $actions=array()) {
        $body = array(
            array('type' => 'TextBlock', 'text' => $title, 'weight' => 'Bolder',
                'size' => 'Medium', 'wrap' => true),
        );
        if ($subtitle)
            $body[] = array('type' => 'TextBlock', 'text' => $subtitle, 'isSubtle' => true,
                'spacing' => 'None', 'wrap' => true);
        if ($facts) {
            $set = array();
            foreach ($facts as $f)
                $set[] = array('title' => (string) $f[0], 'value' => (string) $f[1]);
            $body[] = array('type' => 'FactSet', 'facts' => $set);
        }
        if ($text !== '' && $text !== null)
            $body[] = array('type' => 'TextBlock', 'text' => $text, 'wrap' => true);

        $card = array(
            '$schema' => 'http://adaptivecards.io/schemas/adaptive-card.json',
            'type' => 'AdaptiveCard',
            'version' => '1.4',
            'msteams' => array('width' => 'Full'),
            'body' => $body,
        );
        $acts = array();
        if ($url)
            $acts[] = array('type' => 'Action.OpenUrl', 'title' => __('Open in osTicket'), 'url' => $url);
        foreach ($actions as $a)
            $acts[] = $a;
        if ($acts)
            $card['actions'] = $acts;
        return $card;
    }

    protected function postCard(ConnectorChannel $channel, array $card, $event, $objectType=null, $objectId=null) {
        $url = $channel->getSetting('webhook_url') ?: $this->connector->getSetting('incoming_webhook_url');
        if (!$url)
            return $this->skip($event, __('Channel has no incoming webhook URL'), 'out');
        $payload = array(
            'type' => 'message',
            'attachments' => array(array(
                'contentType' => 'application/vnd.microsoft.card.adaptive',
                'contentUrl' => null,
                'content' => $card,
            )),
        );
        $r = HttpClient::postJson($url, $payload, array(), 10);
        if (!HttpClient::ok($r))
            return $this->fail(HttpClient::describe($r), $event, $objectType, $objectId, $channel);
        return $this->ok($event, null, $objectType, $objectId, null, $channel);
    }

    protected function replyHint(Ticket $ticket) {
        return sprintf(__('Reply from Teams: @%s #%s your message'),
            $this->connector->getSetting('bot_name', 'osTicket'), $ticket->getNumber());
    }

    protected function truncate($text, $max=1500) {
        $text = trim((string) $text);
        return mb_strlen($text) > $max ? mb_substr($text, 0, $max) . ' […]' : $text;
    }

    /* ------------------- Outbound ------------------- */

    function pushTicketCreated(Ticket $ticket, ConnectorChannel $channel) {
        $text = $this->connector->getSetting('include_message', 1)
            ? $this->truncate($this->firstMessageText($ticket)) : '';
        $card = $this->card(sprintf(__('New ticket #%s'), $ticket->getNumber()),
            $this->ticketFacts($ticket), $text, $this->ticketUrl($ticket),
            (string) $ticket->getSubject());
        $card['body'][] = array('type' => 'TextBlock', 'text' => $this->replyHint($ticket),
            'isSubtle' => true, 'size' => 'Small', 'wrap' => true);
        return $this->postCard($channel, $card, 'ticket.created', ConnectorLink::TYPE_TICKET, $ticket->getId());
    }

    function pushEntry(ThreadEntry $entry, Ticket $ticket, ConnectorChannel $channel) {
        switch ($entry->getType()) {
        case 'M':
            $title = sprintf(__('New message on #%s'), $ticket->getNumber());
            break;
        case 'R':
            $title = sprintf(__('Reply sent on #%s'), $ticket->getNumber());
            break;
        default:
            $title = sprintf(__('Internal note on #%s'), $ticket->getNumber());
        }
        $facts = array(
            array(__('By'), $this->posterName($entry)),
            array(__('Subject'), (string) $ticket->getSubject()),
            array(__('Department'), (string) $ticket->getDeptName()),
            array(__('Status'), (string) $ticket->getStatus()),
        );
        $text = $this->connector->getSetting('include_message', 1)
            ? $this->truncate($this->entryText($entry)) : '';
        $card = $this->card($title, $facts, $text, $this->ticketUrl($ticket));
        $card['body'][] = array('type' => 'TextBlock', 'text' => $this->replyHint($ticket),
            'isSubtle' => true, 'size' => 'Small', 'wrap' => true);
        return $this->postCard($channel, $card, 'entry.created', ConnectorLink::TYPE_ENTRY, $entry->getId());
    }

    function pushTicketEvent(Ticket $ticket, $event, array $data, ConnectorChannel $channel) {
        $card = $this->card($this->eventTitle($ticket, $event, $data), array(
            array(__('Subject'), (string) $ticket->getSubject()),
            array(__('Department'), (string) $ticket->getDeptName()),
            array(__('Status'), (string) $ticket->getStatus()),
        ), '', $this->ticketUrl($ticket));
        return $this->postCard($channel, $card, 'ticket.'.$event, ConnectorLink::TYPE_TICKET, $ticket->getId());
    }

    function sendAlert(ConnectorChannel $channel, array $alert) {
        $severity = strtoupper((string) (isset($alert['severity']) ? $alert['severity'] : 'info'));
        $title = sprintf('[%s] %s', $severity, isset($alert['title']) ? $alert['title'] : __('Alert'));
        $facts = array();
        if (!empty($alert['facts']))
            foreach ($alert['facts'] as $f)
                $facts[] = array($f[0], $f[1]);
        $card = $this->card($title, $facts,
            $this->truncate(isset($alert['text']) ? $alert['text'] : ''),
            isset($alert['url']) ? $alert['url'] : null,
            isset($alert['kind']) ? ucfirst($alert['kind']) . (isset($alert['event']) ? ' · ' . $alert['event'] : '') : null);
        return $this->postCard($channel, $card, 'alert.' . (isset($alert['kind']) ? $alert['kind'] : 'system'),
            isset($alert['incident_id']) ? ConnectorLink::TYPE_INCIDENT : (isset($alert['ticket_id']) ? ConnectorLink::TYPE_TICKET : null),
            isset($alert['incident_id']) ? $alert['incident_id'] : (isset($alert['ticket_id']) ? $alert['ticket_id'] : null));
    }

    /* ------------------- Inbound (outgoing webhook) ------------------- */

    function verifySignature(ConnectorRequest $req) {
        $secret = $this->connector->getSetting('outgoing_secret');
        if (!$secret)
            return false;
        $auth = (string) $req->header('authorization');
        if (stripos($auth, 'HMAC ') !== 0)
            return false;
        $provided = trim(substr($auth, 5));
        $key = base64_decode($secret, true);
        if ($key === false)
            $key = $secret;
        $expected = base64_encode(hash_hmac('sha256', $req->raw, $key, true));
        return hash_equals($expected, $provided);
    }

    protected function reply($text) {
        return array('status' => 200, 'json' => array('type' => 'message', 'text' => $text));
    }

    protected function usage() {
        $bot = $this->connector->getSetting('bot_name', 'osTicket');
        return sprintf(__("How to use @%s:\n"
            ."• new <subject> | <details> — open a ticket in this channel's department\n"
            ."• #<number> <message> — reply to a ticket\n"
            ."• note #<number> <message> — add an internal note\n"
            ."• status #<number> — show ticket details\n"
            ."• close #<number> [comment] — close a ticket"), $bot);
    }

    function handleInbound(ConnectorRequest $req) {
        if (!$this->verifySignature($req)) {
            $this->connector->logEvent('in', 'command', 'error', __('Invalid or missing HMAC signature'));
            return array('status' => 401, 'json' => array('type' => 'message',
                'text' => __('Request could not be verified.')));
        }
        $a = is_array($req->json) ? $req->json : array();
        $text = isset($a['text']) ? $a['text'] : '';
        $text = preg_replace('/<at>.*?<\/at>/i', '', $text);
        $text = trim(html_entity_decode(strip_tags($text), ENT_QUOTES, 'UTF-8'));
        $from = isset($a['from']['name']) ? $a['from']['name'] : __('Teams user');
        $activityId = isset($a['id']) ? $a['id'] : md5($req->raw);
        $channelId = isset($a['channelData']['channel']['id']) ? $a['channelData']['channel']['id']
            : (isset($a['channelData']['teamsChannelId']) ? $a['channelData']['teamsChannelId']
            : (isset($a['conversation']['id']) ? preg_replace('/;.*$/', '', $a['conversation']['id']) : ''));

        $channel = ConnectorChannel::lookupByExternal($this->connector->getId(), $channelId);
        if (!$channel || !$channel->isEnabled()) {
            $this->connector->logEvent('in', 'command', 'skipped',
                sprintf(__('Unmapped channel %s'), $channelId));
            return $this->reply(sprintf(__('This channel (%s) is not mapped to a department yet. An administrator can map it under Admin Panel → Manage → Connectors → %s.'),
                $channelId ?: '?', $this->connector->getName()));
        }

        try {
            return $this->command($text, $from, $channel, $activityId);
        }
        catch (Throwable $t) {
            $this->connector->logEvent('in', 'command', 'error', $t->getMessage(), null, null, $activityId, $channel);
            return $this->reply(__('Sorry, something went wrong while processing that command.'));
        }
    }

    protected function command($text, $from, ConnectorChannel $channel, $activityId) {
        if ($text === '' || preg_match('/^(help|\?)$/i', $text))
            return $this->reply($this->usage());

        // status #123
        if (preg_match('/^(status|show|info)\s+#?(\d+)\s*$/i', $text, $m)) {
            if (!($ticket = ConnectorManager::findTicket($m[2], $this->connector)))
                return $this->reply(sprintf(__('Ticket #%s was not found.'), $m[2]));
            $lines = array(sprintf('#%s — %s', $ticket->getNumber(), $ticket->getSubject()));
            foreach ($this->ticketFacts($ticket) as $f)
                $lines[] = sprintf('%s: %s', $f[0], $f[1]);
            $lines[] = $this->ticketUrl($ticket);
            $this->connector->logEvent('in', 'command.status', 'ok', null, ConnectorLink::TYPE_TICKET,
                $ticket->getId(), $activityId, $channel);
            return $this->reply(implode("\n", $lines));
        }

        // close #123 [comment]
        if (preg_match('/^(close|resolve)\s+#?(\d+)\s*(.*)$/is', $text, $m)) {
            if (!($ticket = ConnectorManager::findTicket($m[2], $this->connector)))
                return $this->reply(sprintf(__('Ticket #%s was not found.'), $m[2]));
            if (!$ticket->isOpen())
                return $this->reply(sprintf(__('Ticket #%s is already closed.'), $ticket->getNumber()));
            $errors = array();
            ConnectorManager::beginInbound($this->connector, $channel, $activityId);
            try {
                $comment = trim($m[3]) ? sprintf(__('%s (via Teams): %s'), $from, trim($m[3]))
                    : sprintf(__('Closed by %s via Teams'), $from);
                $ok = $ticket->setStatus(ConnectorManager::closedStatus(), $comment, $errors, false, true);
            }
            finally {
                ConnectorManager::endInbound();
            }
            if (!$ok)
                return $this->reply(sprintf(__('Unable to close ticket #%s: %s'), $ticket->getNumber(),
                    $errors['err'] ?? __('unknown error')));
            $this->connector->logEvent('in', 'command.close', 'ok', $from, ConnectorLink::TYPE_TICKET,
                $ticket->getId(), $activityId, $channel);
            return $this->reply(sprintf(__('Ticket #%s closed.'), $ticket->getNumber()));
        }

        // note #123 text  |  reply #123 text  |  #123 text
        if (preg_match('/^(?:(note|internal|reply)\s+)?#(\d+)\s*[:\-]?\s*(.+)$/is', $text, $m)) {
            if (!($ticket = ConnectorManager::findTicket($m[2], $this->connector)))
                return $this->reply(sprintf(__('Ticket #%s was not found.'), $m[2]));
            $mode = 'auto';
            if (in_array(strtolower($m[1]), array('note', 'internal')))
                $mode = 'note';
            elseif (strtolower($m[1]) == 'reply')
                $mode = 'reply';
            $errors = array();
            $entry = ConnectorManager::postToTicket($this->connector, $ticket, array(
                'body' => trim($m[3]),
                'name' => $from,
                'mode' => $mode,
                'external_id' => $activityId,
                'title' => sprintf(__('From %s via Teams'), $from),
            ), $errors);
            if (!$entry)
                return $this->reply(sprintf(__('Unable to post to ticket #%s: %s'), $ticket->getNumber(),
                    $errors['err'] ?? Format::array_implode(': ', '; ', $errors)));
            $this->connector->logEvent('in', 'command.post', 'ok', $from, ConnectorLink::TYPE_ENTRY,
                $entry->getId(), $activityId, $channel);
            return $this->reply(sprintf(__('%s posted on ticket #%s.'), $this->entryTypeLabel($entry),
                $ticket->getNumber()));
        }

        // new subject | details
        if (preg_match('/^(new|open|ticket)\s*[:\-]?\s*(.+)$/is', $text, $m)) {
            if (!$channel->isInbound())
                return $this->reply(__('This channel is not allowed to open tickets.'));
            $rest = trim($m[2]);
            $subject = $rest;
            $details = '';
            if (strpos($rest, '|') !== false)
                list($subject, $details) = array_map('trim', explode('|', $rest, 2));
            elseif (strpos($rest, "\n") !== false)
                list($subject, $details) = array_map('trim', explode("\n", $rest, 2));
            $errors = array();
            $ticket = ConnectorManager::createTicket($this->connector, $channel, array(
                'subject' => $subject,
                'message' => $details ?: $subject,
                'attribution' => sprintf(__('Reported by %s via Microsoft Teams (%s)'), $from, $channel->getName()),
                'name' => $from,
                'external_id' => $activityId,
            ), $errors);
            if (!$ticket)
                return $this->reply(sprintf(__('Unable to open a ticket: %s'),
                    $errors['err'] ?? Format::array_implode(': ', '; ', $errors)));
            $this->connector->logEvent('in', 'command.new', 'ok', $from, ConnectorLink::TYPE_TICKET,
                $ticket->getId(), $activityId, $channel);
            return $this->reply(sprintf(__("Ticket #%s opened in %s: %s\n%s\n%s"),
                $ticket->getNumber(), $ticket->getDeptName(), $ticket->getSubject(),
                $this->ticketUrl($ticket), $this->replyHint($ticket)));
        }

        return $this->reply(__("I didn't understand that.") . "\n" . $this->usage());
    }
